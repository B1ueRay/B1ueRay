let currentLang = localStorage.getItem('fitmatch_lang') || 'uk';

function t(key) {
  return (I18N[currentLang] && I18N[currentLang][key]) || I18N.uk[key] || key;
}

function setLang(lang) {
  if (!I18N[lang]) return;
  currentLang = lang;
  localStorage.setItem('fitmatch_lang', lang);
  if (typeof onLangChange === 'function') onLangChange();
}
